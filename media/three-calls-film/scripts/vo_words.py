# Word timings for the placed voiceover (faster-whisper word timestamps) → audio/vo_words.json:
# { "<line id>": [[word, start_beat, end_beat], ...] } on the film's beat grid. The film cues sub-events on words with
# W('c3', 'password') → the beat that word starts. Run after vo_build.py.
import json, re, numpy as np, soundfile as sf
from scipy.signal import resample_poly
from faster_whisper import WhisperModel
TL = json.load(open('timeline.json')); BEAT = 60 / float(TL['bpm'])
m = WhisperModel('small.en', device='cpu', compute_type='int8')
out = {}
for p in json.load(open('audio/vo_placed.json')):
    a, sr = sf.read(f"audio/vo/{p['id']}.wav", dtype='float32')
    segs, _ = m.transcribe(resample_poly(a, 1, 3).astype(np.float32), language='en', beam_size=5, word_timestamps=True)
    out[p['id']] = [[re.sub(r'[^a-z0-9\-]', '', w.word.lower()), round((p['t0'] + w.start) / BEAT, 3), round((p['t0'] + w.end) / BEAT, 3)] for s in segs for w in s.words]
json.dump(out, open('audio/vo_words.json', 'w'), indent=0)
print({k: len(v) for k, v in out.items()})
# the film reads the word timings from a generated script, like data.js
with open('film/vowords.js', 'w') as f: f.write('// GENERATED by scripts/vo_words.py, do not edit\nwindow.VOW = ' + json.dumps(out) + ';\n')
